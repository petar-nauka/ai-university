def _num(x, L):
    """A number as the page's language writes it: 1.5 is "1,5" on a Bulgarian page."""
    if x is None:
        return "?"
    return f"{x:g}".replace(".", L["decimal"]) if _is_num(x) else str(x)


def _count(L, x, key):
    """A number with its noun in the right form: 1 час, 2 часа, 1,5 часа; 1 hour, 1.5 hours."""
    one, many = L[key]
    return f"{_num(x, L)} {one if x == 1 else many}"


def _is_num(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def _dict(v) -> dict:
    return v if isinstance(v, dict) else {}


def _list(v) -> list:
    return v if isinstance(v, list) else []


def _records(data, key) -> list[dict]:
    """The dict entries of data[key]. module.json is only checked at the gates, so a page
    may be rendered from records the gates would refuse: show what is there, skip the rest."""
    return [r for r in _list(_dict(data).get(key)) if isinstance(r, dict)]


def _plan(v) -> list[dict]:
    """The days of a study plan that can be shown (the gates check the rest)."""
    return [d for d in _list(v) if isinstance(d, dict) and isinstance(d.get("items"), list)]


_SOURCE_TOKEN = re.compile(r"(?<![\w\[/])S\d+(?![\w\]])")
_TASK_TOKEN = re.compile(r"(?<![\w\[/-])M\d{2}-P\d+(?![\w\]-])")


def _day_links(m, data):
    """What a day item can link to: each source id to its page (a video at the start of its
    first segment in this module), each task id to the module's practice.md."""
    sources = {s["id"]: s for s in _records(data, "sources") if isinstance(s.get("id"), str)}
    urls = {}
    for r in _records(data, "resources"):
        s = sources.get(r.get("source_id"))
        if not s or r["source_id"] in urls:
            continue
        vid = _dict(s.get("video")).get("video_id")
        start = _dict(r.get("locator")).get("start_sec")
        if r.get("role") == "video" and vid:
            urls[r["source_id"]] = watch_url(vid, start if _is_num(start) else None)
        elif isinstance(s.get("url"), str) and s["url"]:
            urls[r["source_id"]] = s["url"]
    for sid, s in sources.items():   # a source a task names but no resource carries
        if sid not in urls and isinstance(s.get("url"), str) and s["url"]:
            urls[sid] = s["url"]
    tasks = {t["id"] for t in _records(data, "practice") if isinstance(t.get("id"), str)}
    return {"urls": urls, "tasks": tasks, "slug": m["slug"]}


def _link_item(text, links, prefix):
    if not links:
        return text
    text = _SOURCE_TOKEN.sub(lambda mo: f"[{mo.group(0)}]({links['urls'][mo.group(0)]})"
                             if mo.group(0) in links["urls"] else mo.group(0), text)
    return _TASK_TOKEN.sub(lambda mo: f"[{mo.group(0)}]({prefix}practice.md)"
                           if mo.group(0) in links["tasks"] else mo.group(0), text)


def _day_header(c, with_part):
    L = c.L
    return ([L["col_day"], L["col_week"]] + ([L["col_dates"]] if c.brief.get("start_date") else [])
            + ([L["col_part"]] if with_part else []) + [L["col_minutes"], L["col_todo"]])


def _day_rows(c, unit, with_part):
    """Table rows for one unit's days; a unit without a plan gets one row announcing its days."""
    L, start = c.L, c.brief.get("start_date")
    uid, first, n, hours, plan, links = unit
    part = [uid or L["capstone"]] if with_part else []
    prefix = f"modules/{links['slug']}/" if links and with_part else ""
    if plan:
        rows = []
        for i, d in enumerate(plan):
            day = first + i
            todo = "; ".join(_link_item(str(x), links, prefix) for x in d["items"] if x)
            if uid in c.remind and i == len(plan) - 1:   # added after linking: M02 stays plain
                todo = f"{_reminder(c, 'remind', c.remind[uid])} {todo}"
            rows.append([day, day_week(day, c.dpw)] + ([day_date(start, day, c.dpw)] if start else [])
                        + part + [_num(d.get("minutes"), L), todo])
        return rows
    last = first + n - 1
    days = str(first) if n == 1 else f"{first}–{last}"
    weeks = format_weeks((day_week(first, c.dpw), day_week(last, c.dpw)))
    dates = [f"{day_date(start, first, c.dpw)} – {day_date(start, last, c.dpw)}"] if start else []
    return [[days, weeks] + dates + part + [_num(hours * 60, L), L["plan_pending"]]]


def _reminder(c, key, nxt):
    return c.L[key].format(course=c.title, id=nxt["id"], title=nxt["title"], day=nxt["day"])


def _cell(x):
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out


class _Ctx:
    """Everything the pages need, loaded up front so a failure leaves nothing half-written."""

    def __init__(self, course_dir, today):
        self.course_dir = Path(course_dir)
        self.course = load_course(self.course_dir)
        self.benchmarks = load_benchmarks(self.course_dir)
        # The syllabus rules guarantee every course.json field the pages rely on, and safe
        # module slugs for the write paths: refuse while any of them fails.
        errors = [p for p in validate_syllabus(self.course, self.benchmarks) if p.level == "error"]
        if errors:
            raise RenderError("The syllabus has errors; run aiu validate --stage syllabus and fix "
                              "them before rendering", errors)
        self.brief = self.course["brief"]
        self.title = self.course.get("title") or self.brief["topic"]
        self.L = LABELS.get(str(self.brief["language"]).split("-")[0].lower(), LABELS["en"])
        self.today = today or date.today().isoformat()
        self.mods = []
        for m in self.course["modules"]:
            path = module_dir(self.course_dir, self.course, m["id"]) / "module.json"
            if path.exists():
                try:
                    data = read_json(path)
                except StoreError as e:
                    raise RenderError(f"Cannot render {m['id']}: {e}")
                if not isinstance(data, dict):
                    raise RenderError(f"Cannot render {m['id']}: module.json is not a JSON object")
            else:
                data = empty_module(m["id"])
            self.mods.append((m, data))
        hours = self.course["capstone"]["hours"]
        self.alloc = allocate_weeks([m["hours"] for m in self.course["modules"]], hours,
                                    self.brief["hours_per_week"])
        # Study days: each module's plan in order, then the capstone's, numbered across the course.
        dpw = self.brief.get("days_per_week")
        self.dpw = dpw if isinstance(dpw, int) and 1 <= dpw <= 7 else DEFAULT_DAYS_PER_WEEK
        self.day_min = day_minutes(self.brief)
        units = [(m["id"], m["hours"], _plan(data.get("study_plan")), _day_links(m, data))
                 for m, data in self.mods]
        if hours > 0:
            units.append((None, hours, _plan(self.course["capstone"].get("study_plan")), None))
        self.days, first = [], 1
        for uid, h, plan, links in units:
            n = plan_days(plan, h, self.day_min)
            self.days.append((uid, first, n, h, plan, links))
            first += n
        # Building by module: the last day of a module with a plan asks the learner to request
        # the next module, for as long as that one is not verified.
        self.remind = {}
        if build_mode(self.brief) == "incremental":
            for (m, _), (nxt, ndata), unit in zip(self.mods, self.mods[1:], self.days):
                if unit[4] and ndata.get("status") != "verified":
                    self.remind[m["id"]] = {"id": nxt["id"], "title": nxt["title"],
                                            "day": unit[1] + len(unit[4]) - 1}

    def status(self, data):
        status = data.get("status")
        return self.L[status] if status in STATUSES else str(status)


def _render_readme(c):
    L, course, brief = c.L, c.course, c.brief
    out = [f"**{L['start_here']}**", "", f"# {c.title}", "",
           f"**{L['goal']}:** {brief.get('goal', '')}", "",
           f"- {L['level']}: {L['levels'].get(brief.get('level'), brief.get('level', ''))}",
           f"- {L['budget']}: {_num(brief.get('hours_per_week'), L)} {L['per_week']}, "
           f"{_count(L, brief.get('weeks'), 'weeks_word')}",
           f"- {L['session']}: {_num(brief.get('session_minutes'), L)} {L['minutes']}",
           f"- {L['study_days']}: {c.dpw} {L['days_week']} {_num(round(c.day_min), L)} {L['per_day']}"
           f" ([{L['by_day']}](schedule.md))"]
    if c.remind:
        out.append(f"- {_reminder(c, 'next_up', next(iter(c.remind.values())))}")
    out += ["", f"## {L['how_to']}", ""]
    out += [f"{i}. {s}" for i, s in enumerate(L["how_steps"], 1)]
    out += ["", f"## {L['modules']}", ""]
    rows = []
    for i, ((m, data), span) in enumerate(zip(c.mods, c.alloc["modules"]), 1):
        rows.append([i, f"[{m['title']}](modules/{m['slug']}/README.md)", format_weeks(span),
                     _num(m["hours"], L), c.status(data)])
    out += _table([L["col_no"], L["col_title"], L["col_weeks"], L["col_hours"], L["col_status"]], rows)
    cap = course.get("capstone") or {}
    if cap.get("title"):
        out += ["", f"## {L['capstone']}", "", f"**{cap['title']}**"]
        if cap.get("deliverable"):
            out.append(f"- {L['deliverable']}: {cap['deliverable']}")
        if c.alloc["capstone"]:
            out.append(f"- {L['col_hours']}: {_num(cap['hours'], L)} · {L['col_weeks']}: "
                       f"{format_weeks(c.alloc['capstone'])}")
        out.append("- [capstone.md](capstone.md)")
    if brief.get("assumptions"):
        out += ["", f"## {L['assumptions']}", ""] + [f"- {a}" for a in brief["assumptions"]]
    n_out = sum(len(m["outcomes"]) for m, _ in c.mods)
    n_vid = sum(1 for _, d in c.mods for r in _records(d, "resources") if r.get("role") == "video")
    n_read = sum(1 for _, d in c.mods for r in _records(d, "resources") if r.get("role") == "reading")
    n_task = sum(len(_records(d, "practice")) for _, d in c.mods)
    out += ["", f"## {L['pages']}", "",
            f"- [{L['link_syllabus']}](syllabus.md)", f"- [{L['link_schedule']}](schedule.md)",
            f"- [{L['link_sources']}](sources.md)", f"- [{L['link_glossary']}](glossary.md)",
            f"- [{L['link_gaps']}](gaps.md)", "",
            f"{L['counts']}: {n_out} {L['n_outcomes']}, {n_vid} {L['n_videos']}, "
            f"{n_read} {L['n_readings']}, {n_task} {L['n_tasks']}.", "",
            f"{L['assembled']} {c.today}. {L['tutor_note']}"]
    return out


def _render_syllabus(c):
    L = c.L
    out = [f"# {L['syllabus']}: {c.title}", ""]
    for i, (m, _) in enumerate(c.mods, 1):
        out += [f"## {L['module']} {i} · {m['title']}", "", m.get("summary", ""), "",
                f"- {L['col_hours']}: {_num(m['hours'], L)}",
                f"- {L['prerequisites']}: {', '.join(m.get('prerequisites') or []) or L['none']}"]
        if m.get("topics"):
            out.append(f"- {L['topics']}: {'; '.join(m['topics'])}")
        out.append("")
        for o in m["outcomes"]:
            if o.get("origin") == "benchmark":
                origin = ", ".join(o.get("benchmark_refs") or []) or L["benchmark"]
            else:
                origin = L["ai_designed"]
            out.append(f"- **{o['id']}** {o['statement']} ({L['origin']}: {origin})")
        out.append("")
    cap = c.course.get("capstone") or {}
    if cap.get("title"):
        out += [f"## {L['capstone']}", "", f"**{cap['title']}**"]
        if cap.get("deliverable"):
            out.append(f"- {L['deliverable']}: {cap['deliverable']}")
        out.append("")
    if c.course.get("out_of_scope"):
        out += [f"## {L['out_of_scope']}", ""] + [f"- {x}" for x in c.course["out_of_scope"]] + [""]
    return out


def _render_schedule(c):
    L, start = c.L, c.brief.get("start_date")
    header = [L["col_part"], L["col_weeks"], L["col_hours"]] + ([L["col_dates"]] if start else [])
    entries = [(f"{m['id']} · {m['title']}", span, m["hours"])
               for (m, _), span in zip(c.mods, c.alloc["modules"])]
    cap = c.course.get("capstone") or {}
    if c.alloc["capstone"]:
        name = f"{L['capstone']}: {cap['title']}" if cap.get("title") else L["capstone"]
        entries.append((name, c.alloc["capstone"], cap["hours"]))
    rows = []
    for name, span, hours in entries:
        row = [name, format_weeks(span), _num(hours, L)]
        if start:
            row.append(f"{week_dates(start, span[0])[0]} – {week_dates(start, span[1])[1]}")
        rows.append(row)
    total = c.alloc["total_weeks"]
    out = [f"# {L['schedule']}", ""] + _table(header, rows) + ["", f"{L['total_weeks']}: {total}"]
    planned = c.brief.get("weeks")
    if planned and total > planned:
        out += ["", f"{L['over_budget']} ({total} > {_num(planned, L)})."]
    rows = [r for unit in c.days for r in _day_rows(c, unit, with_part=True)]
    out += ["", f"## {L['by_day']}", "", L["by_day_intro"], ""] + _table(_day_header(c, True), rows)
    return out


def _task_block(L, t):
    parts = [f"**{t.get('id', '?')}**"]
    if t.get("title"):
        parts.append(str(t["title"]))
    if _is_num(t.get("minutes")):
        parts.append(f"{_num(t['minutes'], L)} {L['minutes']}")
    if t.get("deliverable"):
        parts.append(f"{L['turn_in']}: {t['deliverable']}")
    out = ["- " + " · ".join(parts)]
    criteria = [k for k in _list(t.get("criteria")) if isinstance(k, dict)]
    if criteria:
        crit = " · ".join(f"{k.get('text', '')} ({_num(k.get('points'), L)} {L['pts']})"
                          for k in criteria)
        out.append(f"  {L['criteria']}: {crit}")
    return out


def _glossary_line(g):
    term, term_en = g.get("term", ""), g.get("term_en")
    en = f" ({term_en})" if term_en and term_en != term else ""
    return f"- **{term}**{en}: {g.get('definition', '')}"


def _render_resource(L, r, sources):
    sid = r.get("source_id")
    s = sources.get(sid, {}) if isinstance(sid, str) else {}
    title = s.get("title") or sid or ""
    role, loc = r.get("role"), _dict(r.get("locator"))
    start, end = loc.get("start_sec"), loc.get("end_sec")
    out = []
    if role == "video":
        vid = _dict(s.get("video")).get("video_id")
        url = watch_url(vid, start if _is_num(start) else None) if vid else s.get("url", "")
        span = ""
        if _is_num(start) and _is_num(end):
            span = f" [{format_ts(start)}–{format_ts(end)}]"
        out.append(f"- **{L['watch']}:** [{title}]({url}){span}")
        if r.get("before_question"):
            out.append(f"  - {L['before']}: {r['before_question']}")
        if r.get("after_task"):
            out.append(f"  - {L['after']}: {r['after_task']}")
    else:
        label = L[role] if role in ("reference", "tool") else L["read"]
        section = f" ({L['section']} {loc['section']})" if loc.get("section") else ""
        out.append(f"- **{label}:** [{title}]({s.get('url', '')}) ({r.get('source_id')}){section}")
    if r.get("note"):
        out.append(f"  - {r['note']}")
    return out


def _render_module(c, index, m, data):
    L = c.L
    sources = {s["id"]: s for s in _records(data, "sources") if isinstance(s.get("id"), str)}
    resources, practice = _records(data, "resources"), _records(data, "practice")
    gaps = _records(data, "gaps")
    span = c.alloc["modules"][index]
    week_label = L["week_label"][0 if span[0] == span[1] else 1]
    out = [f"# {L['module']} {index + 1} · {m['title']}", "",
           f"{week_label} {format_weeks(span)} · {_count(L, m['hours'], 'hours')} · "
           f"{L['col_status']}: {c.status(data)}", ""]
    if m.get("summary"):
        out += [m["summary"], ""]
    if m.get("prerequisites"):
        out += [f"{L['prerequisites']}: {', '.join(m['prerequisites'])}", ""]
    out += ["[lesson.md](lesson.md) · [practice.md](practice.md)", ""]
    if data.get("status") == "planned" and not resources and not practice:
        out += [f"_{L['empty_module']}_", ""]
    unit = c.days[index]
    if unit[4]:
        out += [f"## {L['by_day']}", ""] + _table(_day_header(c, False),
                                                  _day_rows(c, unit, with_part=False)) + [""]
    outcome_ids = {o["id"] for o in m["outcomes"]}
    for o in m["outcomes"]:
        out += [f"## {L['outcome']} {o['id']}", "", o["statement"], ""]
        for r in resources:
            if r.get("outcome_id") == o["id"]:
                out += _render_resource(L, r, sources)
        guided = [t for t in practice
                  if t.get("kind") == "guided" and o["id"] in _list(t.get("outcome_ids"))]
        if guided:
            out.append(f"- **{L['practice']}:**")
            for t in guided:
                out += ["  " + ln for ln in _task_block(L, t)]
        for g in gaps:
            if g.get("outcome_id") == o["id"]:
                out.append(f"- **{L['gap']} ({g.get('kind')}):** {g.get('note', '')}")
        out.append("")
    for kind in ("independent", "project", "recall"):
        tasks = [t for t in practice if t.get("kind") == kind]
        if tasks:
            out += [f"## {L[kind]}", ""]
            for t in tasks:
                out += _task_block(L, t)
            out.append("")
    other = [g for g in gaps if not (isinstance(g.get("outcome_id"), str)
                                     and g["outcome_id"] in outcome_ids)]
    if other:
        out += [f"## {L['module_gaps']}", ""] + [f"- {g.get('kind')}: {g.get('note', '')}" for g in other] + [""]
    glossary = _records(data, "glossary")
    if glossary:
        out += [f"## {L['glossary']}", ""] + [_glossary_line(g) for g in glossary] + [""]
    out += [f"## {L['selfcheck']}", ""] + [f"- [ ] {o['statement']}" for o in m["outcomes"]]
    return out


def _source_rows(prefix, sources):
    return [[f"{prefix}{s.get('id', '?')}", s.get("title"), s.get("author"), s.get("published") or "",
             s.get("url"), s.get("reliability"), s.get("access")] for s in sources]


def _render_sources(c):
    L = c.L
    header = [L["col_id"], L["col_title"], L["col_author"], L["col_date"], L["col_link"],
              L["col_reliability"], L["col_access"]]
    out = [f"# {L['sources']}", "", f"## {L['benchmarks']}", ""]
    out += _table(header, _source_rows("", _records(c.benchmarks, "sources")))
    for m, data in c.mods:
        out += ["", f"## {m['id']} · {m['title']}", ""]
        out += _table(header, _source_rows(f"{m['id']}:", _records(data, "sources")))
    return out


def _render_glossary(c):
    seen, entries = set(), []
    for _, data in c.mods:
        for g in _records(data, "glossary"):
            term = g.get("term")
            if not (isinstance(term, str) and term.strip()):
                continue
            if term.casefold() not in seen:
                seen.add(term.casefold())
                entries.append(g)
    entries.sort(key=lambda g: g["term"].casefold())
    return [f"# {c.L['glossary_page']}", ""] + [_glossary_line(g) for g in entries]


def _render_gaps(c):
    L = c.L
    gaps, weak, bad = [], [], []
    labelled = [("", _records(c.benchmarks, "sources"))]
    for m, data in c.mods:
        for g in _records(data, "gaps"):
            gaps.append(f"- {m['id']} / {g.get('outcome_id') or '-'} ({g.get('kind')}): {g.get('note', '')}")
        labelled.append((f"{m['id']}:", _records(data, "sources")))
    for prefix, sources in labelled:
        for s in sources:
            ident = f"{prefix}{s.get('id', '?')}"
            if s.get("access") in WEAK_ACCESS:
                weak.append(f"- {ident} {s.get('title')}: {s.get('access')} ({s.get('url')})")
            status = _dict(s.get("check")).get("status")
            if status in BAD_CHECK:
                bad.append(f"- {ident} {s.get('title')}: {L['check']} {status} ({s.get('url')})")
    out = [f"# {L['gaps']}", ""]
    for title, lines in ((L["gap_list"], gaps), (L["weak_access"], weak), (L["bad_check"], bad)):
        out += [f"## {title}", ""] + (lines or [L["no_gaps"]]) + [""]
    note = _dict(c.benchmarks).get("note")
    if note:
        out += [f"## {L['benchmark_note']}", "", str(note), ""]
    return out


def _page(name: str, build, *args) -> list[str]:
    """Build one page; a record shaped in a way the renderer did not expect becomes a
    RenderError naming the page and the field instead of a bare KeyError."""
    try:
        return build(*args)
    except (KeyError, TypeError, AttributeError, ValueError, IndexError) as exc:
        raise RenderError(f"Cannot render {name}: a record has a missing or malformed field "
                          f"({type(exc).__name__}: {exc}); run aiu validate and fix it") from exc


def render_course(course_dir: Path, today: str | None = None) -> list[str]:
    c = _Ctx(course_dir, today)
    pages = {rel: _page(rel, build, c) for rel, build in (
        ("README.md", _render_readme), ("syllabus.md", _render_syllabus),
        ("schedule.md", _render_schedule), ("sources.md", _render_sources),
        ("glossary.md", _render_glossary), ("gaps.md", _render_gaps))}
    for i, (m, data) in enumerate(c.mods):
        rel = f"modules/{m['slug']}/README.md"
        pages[rel] = _page(f"{rel} (module {m['id']})", _render_module, c, i, m, data)
    from .site import site_pages
    for rel, text in _page("web pages", site_pages, c).items():
        pages[rel] = text.splitlines()
    for rel in pages:
        path = c.course_dir / rel
        if path.exists() and not path.read_bytes().decode("utf-8", "replace").startswith(GENERATED_MARK):
            raise RenderError(f"Refusing to overwrite hand-written file: {rel}")
    for rel, lines in pages.items():
        path = c.course_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(GENERATED_MARK + "\n" + "\n".join(lines).rstrip("\n") + "\n")
    return sorted(pages)
